--changeset janmeter:001-create-entity-tables
CREATE TABLE IF NOT EXISTS janmeter_parties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_type VARCHAR(255),
    abbreviation VARCHAR(255),
    party VARCHAR(255),
    created_datetime TIMESTAMP,
    updated_datetime TIMESTAMP
);

CREATE TABLE IF NOT EXISTS janmeter_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statename VARCHAR(255),
    type VARCHAR(255),
    createddatetime TIMESTAMP,
    updateddatetime TIMESTAMP
);

CREATE TABLE IF NOT EXISTS janmeter_district (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    districtname VARCHAR(255),
    state_id BIGINT,
    createddatetime TIMESTAMP,
    updateddatetime TIMESTAMP,
    CONSTRAINT fk_janmeter_district_state FOREIGN KEY (state_id) REFERENCES janmeter_state (id)
);

CREATE TABLE IF NOT EXISTS janmeter_taluka (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    talukaname VARCHAR(255),
    district_id BIGINT,
    createddatetime TIMESTAMP,
    updateddatetime TIMESTAMP,
    CONSTRAINT fk_janmeter_taluka_district FOREIGN KEY (district_id) REFERENCES janmeter_district (id)
);

CREATE TABLE IF NOT EXISTS janmeter_village_city (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    iscity BOOLEAN NOT NULL,
    taluka_id BIGINT,
    createddatetime TIMESTAMP,
    updateddatetime TIMESTAMP,
    CONSTRAINT fk_janmeter_village_city_taluka FOREIGN KEY (taluka_id) REFERENCES janmeter_taluka (id)
);

CREATE TABLE IF NOT EXISTS janmeter_ward (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    village_city_id BIGINT,
    createddatetime TIMESTAMP,
    updateddatetime TIMESTAMP,
    CONSTRAINT fk_janmeter_ward_village_city FOREIGN KEY (village_city_id) REFERENCES janmeter_village_city (id)
);

CREATE TABLE IF NOT EXISTS janmeter_party_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    createddatetime TIMESTAMP,
    updateddatetime TIMESTAMP
);

