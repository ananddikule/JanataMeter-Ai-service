--changeset janmeter:005-deduplicate-states
WITH ranked_states AS (
    SELECT id,
           FIRST_VALUE(id) OVER (
               PARTITION BY LOWER(BTRIM(statename)), type
               ORDER BY id
           ) AS canonical_id,
           ROW_NUMBER() OVER (
               PARTITION BY LOWER(BTRIM(statename)), type
               ORDER BY id
           ) AS row_number
    FROM janmeter_state
)
UPDATE janmeter_district district
SET state_id = ranked_states.canonical_id
FROM ranked_states
WHERE district.state_id = ranked_states.id
  AND ranked_states.row_number > 1;

